from enum import Enum

from pydantic import BaseModel, Field


class TaskType(str, Enum):
    """Supported research task categories."""

    SOURCE_DISCOVERY = "SOURCE_DISCOVERY"
    EVIDENCE_COLLECTION = "EVIDENCE_COLLECTION"
    ANALYSIS = "ANALYSIS"
    VERIFICATION = "VERIFICATION"
    CONFLICT_ANALYSIS = "CONFLICT_ANALYSIS"
    SYNTHESIS = "SYNTHESIS"


class ResearchTaskPlan(BaseModel):
    """A single task produced by the research planner."""

    task_id: str = Field(
        min_length=1,
        max_length=100,
    )

    task_type: TaskType

    description: str = Field(
        min_length=1,
        max_length=2000,
    )

    research_question: str = Field(
        min_length=1,
        max_length=2000,
    )

    expected_outputs: list[str] = Field(
        min_length=1,
        max_length=20,
    )

    dependencies: list[str] = Field(
        default_factory=list,
        max_length=20,
    )

    required: bool = True


class SourcePolicy(BaseModel):
    """Rules governing acceptable research sources."""

    allowed_source_types: list[str] = Field(
        min_length=1,
        max_length=20,
    )

    minimum_sources: int = Field(
        ge=1,
        le=100,
    )

    require_independent_sources: bool = True

    allow_duplicate_sources: bool = False


class CompletionCriteria(BaseModel):
    """Conditions used by the orchestrator to determine completion."""

    required_task_ids: list[str] = Field(
        min_length=1,
        max_length=100,
    )

    minimum_evidence_items: int = Field(
        ge=0,
        le=10000,
    )

    minimum_verified_claims: int = Field(
        ge=0,
        le=10000,
    )


class ResearchPlan(BaseModel):
    """
    Structured research plan generated by the Planner.

    The plan is consumed by the Orchestrator.
    """

    research_goal: str = Field(
        min_length=1,
        max_length=4000,
    )

    assumptions: list[str] = Field(
        default_factory=list,
        max_length=50,
    )

    research_questions: list[str] = Field(
        min_length=1,
        max_length=50,
    )

    tasks: list[ResearchTaskPlan] = Field(
        min_length=1,
        max_length=100,
    )

    source_policy: SourcePolicy

    completion_criteria: CompletionCriteria

    risk_flags: list[str] = Field(
        default_factory=list,
        max_length=50,
    )